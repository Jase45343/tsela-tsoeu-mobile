/**
 * Domain types shared by the mobile app and the server.
 *
 * All money is an integer number of lisente (1 Loti = 100 lisente).
 * All calendar dates are ISO strings (YYYY-MM-DD) in Africa/Maseru.
 * The app records payments received outside it; nothing here moves money.
 */

export type Lisente = number;
/** Calendar date, YYYY-MM-DD, Africa/Maseru. */
export type ISODate = string;
/** Instant, full ISO-8601 with offset (normally UTC "Z"). */
export type ISODateTime = string;

export type StudentStatus = 'active' | 'inactive';

export interface Student {
  id: string;
  name: string;
  parentName: string;
  parentPhone: string; // +266XXXXXXXX
  school: string;
  pickupLocation: string;
  dropoffLocation: string;
  monthlyFee: Lisente;
  onboardedAt: ISODate;
  status: StudentStatus;
}

/**
 * server      — generated by the server on the 1st (authoritative)
 * onboarding  — a new student's first period, created at onboarding (authoritative, BR-6)
 * provisional — created on a device that was offline across the 1st (replaced on sync)
 */
export type PeriodOrigin = 'server' | 'onboarding' | 'provisional';

export interface BillingPeriod {
  id: string;
  studentId: string;
  year: number;
  month: number; // 1-12
  periodStart: ISODate;
  periodEnd: ISODate;
  dueDate: ISODate;
  amountDue: Lisente;
  cancelled: boolean;
  origin: PeriodOrigin;
  /** Set when the holiday rule leaves this month's charge for the driver to decide. */
  needsReview?: boolean;
  /** Why the charge is what it is, e.g. "8 of 21 school days" or the driver's reason for a change. */
  chargeNote?: string | null;
}

export type PeriodStatus = 'unpaid' | 'partial' | 'paid' | 'cancelled';

export type PaymentSource = 'manual' | 'voice';

export interface Payment {
  id: string;
  studentId: string;
  amount: Lisente;
  method: string;
  paymentDate: ISODate;
  reference?: string | null;
  note?: string | null;
  source: PaymentSource;
  createdAt: ISODateTime;
  voidedAt?: ISODateTime | null;
  voidReason?: string | null;
  /** Set on a replacement record created by a correction (FR-016). */
  correctsPaymentId?: string | null;
  acknowledgementNumber?: string | null;
}

export type CreditAdjustmentType = 'refunded_outside_app' | 'written_off' | 'other';

export interface CreditAdjustment {
  id: string;
  studentId: string;
  type: CreditAdjustmentType;
  amount: Lisente;
  reason: string;
  createdAt: ISODateTime;
}

export interface Allocation {
  paymentId: string;
  /** A billing period id, or a credit adjustment id when target is 'adjustment'. */
  targetId: string;
  target: 'period' | 'adjustment';
  amount: Lisente;
}

export interface PeriodState {
  periodId: string;
  amountRecorded: Lisente;
  balance: Lisente;
  status: PeriodStatus;
}

export interface OperatorSettings {
  /** Day of month a period falls due (1-28). Default 1. */
  dueDay: number;
  /** Days after due date before a period counts as overdue. Default 7. */
  graceDays: number;
}

export const DEFAULT_SETTINGS: OperatorSettings = { dueDay: 1, graceDays: 7 };

/**
 * How a student's first month is charged when they start partway through it.
 * full       — always the full monthly fee
 * ask        — the driver chooses each time (full, half, free or another amount)
 * half_after — half the fee if they start on or after the cut-off day
 * prorata    — only the school days left in the month
 */
export type FirstMonthRule = 'full' | 'ask' | 'half_after' | 'prorata';

/**
 * How months with school holidays are charged.
 * same        — the same fee every month, holidays or not
 * by_days     — the fee scaled by the school days the bus runs
 * half_or_ask — full fee if the bus runs at least half the month; otherwise the driver decides
 */
export type HolidayRule = 'same' | 'by_days' | 'half_or_ask';

/** A period when a school is closed, first to last closed day inclusive. school null = every school. */
export interface SchoolClosure {
  id: string;
  school: string | null;
  from: ISODate;
  to: ISODate;
  label: string;
}

export interface BillingRules {
  firstMonthRule: FirstMonthRule;
  halfCutoffDay: number;
  holidayRule: HolidayRule;
  closures: SchoolClosure[];
}

/** Matches what most drivers do today: the full fee, every month. */
export const DEFAULT_BILLING_RULES: BillingRules = { firstMonthRule: 'full', halfCutoffDay: 15, holidayRule: 'same', closures: [] };

export const DEFAULT_PAYMENT_METHODS = ['Cash', 'M-Pesa', 'EcoCash', 'Bank Transfer', 'Other'] as const;

export type AccountStatus = 'current' | 'in_arrears' | 'in_advance';

export type FirstPeriodChoice = 'full' | 'half' | 'prorata' | 'free' | 'custom';
